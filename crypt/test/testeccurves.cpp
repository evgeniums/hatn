template <typename HandlerT>
void eachPluginWithSignature(HandlerT&& handler)
{
    CryptPluginTest::instance().eachPlugin<CryptTestTraits>(
        [&handler](std::shared_ptr<CryptPlugin>& plugin)
        {
            if (plugin->isFeatureImplemented(Crypt::Feature::Signature))
            {
                handler(plugin);
            }
        }
    );
}

// A key counts as refused when it either fails to import or fails validate().
// Returns true if refused; sets stage to where it happened.
bool refusedPublicKey(std::shared_ptr<CryptPlugin>& plugin, const ByteArray& der, std::string& stage)
{
    auto key=plugin->createPublicKey();
    BOOST_REQUIRE(key);
    auto ec=key->importFromBuf(der,ContainerFormat::DER);
    if (ec)
    {
        stage="import";
        return true;
    }
    ec=key->validate();
    if (ec)
    {
        stage="validate";
        return true;
    }
    return false;
}

