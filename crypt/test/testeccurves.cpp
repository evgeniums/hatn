struct CurveCase
{
    const char* curve;
    const char* digest;
};

// the digest is the one commonly paired with the curve
const std::vector<CurveCase>& curveCases()
{
    static const std::vector<CurveCase> cases{
        {"secp256r1","sha256"},
        {"secp384r1","sha256"},
        {"secp521r1","sha512"}
    };
    return cases;
}

std::string ecName(const CurveCase& c)
{
    return fmt::format("EC/{}",c.curve);
}

ByteArray fromHex(const char* hex)
{
    ByteArray raw;
    ContainerUtils::hexToRaw(lib::string_view{hex,strlen(hex)},raw);
    return raw;
}

